from __future__ import annotations

import logging

from fastapi import Depends, FastAPI, HTTPException, Request, Response, status
from fastapi.middleware.cors import CORSMiddleware

from app.chat import (
    MiaChatError,
    MiaChatRequest,
    MiaChatResponse,
    SessionSummaryRequest,
    SessionSummaryResponse,
    ask_mia,
    rate_limiter,
    summarize_session,
)
from app.config import Settings
from app.schemas import LearningContext, SpeechRequest, VoiceSessionResponse
from app.security import (
    AuthenticatedLearner,
    _is_local_development_request,
    require_learner,
)
from app.tts import CartesiaError, synthesize
from app.voice_sessions import create_voice_session


logger = logging.getLogger("eloqia.api")

settings = Settings.from_env()


app = FastAPI(
    title="Eloqia AI API",
    description=(
        "Backend API for Eloqia AI and Mia's realtime "
        "learning experiences."
    ),
    version="1.0.0",
)

# Flutter Web runs on another origin (e.g. http://localhost:5000): without
# CORS the browser blocks every call to this API.
app.add_middleware(
    CORSMiddleware,
    allow_origins=list(settings.allowed_origins),
    allow_credentials=False,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["Authorization", "Content-Type"],
)


# ============================================================================
# SYSTEM
# ============================================================================


@app.get(
    "/health",
    tags=["system"],
)
async def health_check() -> dict[str, object]:
    """
    Return the current backend health state.

    This endpoint intentionally does not require authentication so
    infrastructure and local development tools can verify that the API
    process is alive.
    """

    missing = settings.missing_session_settings()

    if missing:
        return {
            "status": "degraded",
            "service": "eloqia-api",
            "voice_service": "not_ready",
        }

    return {
        "status": "ok",
        "service": "eloqia-api",
        "voice_service": "ready",
    }


