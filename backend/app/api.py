@app.get("/v1/voice/speech/status", tags=["voice"])
async def speech_status(request: Request) -> dict[str, object]:
    """Tells the app whether "Hear Mia" can use the Cartesia voice."""
    current = Settings.from_env()
    # Same rule as require_learner: OIDC, or Evan's local development mode
    # (ELOQIA_ENV=development + ELOQIA_ALLOW_LOCAL_AUTH=true, from 127.0.0.1).
    auth_ready = (
        not current.missing_oidc_settings()
        or _is_local_development_request(request)
    )
    return {
        "available": bool(current.cartesia_api_key) and auth_ready,
        "provider": "cartesia",
        "model": current.cartesia_model,
    }


@app.post(
    "/v1/voice/speech",
    response_class=Response,
    responses={200: {"content": {"audio/wav": {}}}},
    tags=["voice"],
)
async def speak_as_mia(
    payload: SpeechRequest,
    learner: AuthenticatedLearner = Depends(require_learner),
) -> Response:
    """Returns one of Mia's lines as WAV audio generated by Cartesia."""
    current = Settings.from_env()

    if not current.cartesia_api_key:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"code": "speech_not_configured"},
        )

    try:
        audio = await synthesize(
            payload.text,
            payload.style,
            payload.other_speaker,
            payload.speed_factor,
            current,
        )
    except CartesiaError as error:
        logger.warning("Cartesia speech failed: %s", error)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail={"code": "speech_provider_failed"},
        ) from None

    return Response(
        content=audio,
        media_type="audio/wav",
        headers={"Cache-Control": "no-store"},
    )


